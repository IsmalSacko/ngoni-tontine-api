            <h1>Politique de confidentialité</h1>
            <p class="muted">Ngoni Tontine · dernière mise à jour : 19 octobre 2026</p>
            <p>Cette politique décrit les données que l'application Ngoni Tontine (éditée par ISMAELDEV EI, Bamako) collecte, pourquoi, et ce que vous pouvez en faire. L'application note les tontines, les cotisations et les caisses d'association : elle ne fait circuler aucun argent.</p>

            <h2>Données collectées</h2>
            <ul>
                <li><strong>Votre compte</strong> : nom, numéro de téléphone (votre identifiant de connexion), code PIN, adresse e-mail et photo de profil si vous les ajoutez.</li>
                <li><strong>Vos caisses</strong> : groupes, caisses, montants, fréquences, tours, bénéficiaires, cotisations, dons et dépenses que vous ou le bureau enregistrez.</li>
                <li><strong>Les membres</strong> : le nom et le numéro de téléphone des membres que le bureau inscrit. Quand vous choisissez un contact du téléphone pour inscrire un membre, seul ce contact est lu ; le carnet d'adresses n'est jamais lu ni envoyé en entier.</li>
                <li><strong>Les paiements déclarés</strong> : montant, date, moyen de paiement, référence et, si vous l'ajoutez, la photo du reçu. Cette photo n'est visible que par vous et par le bureau de la caisse.</li>
                <li><strong>Les demandes d'adhésion</strong> : quand vous scannez une invitation, votre nom et votre numéro sont transmis au bureau, qui accepte ou refuse.</li>
            </ul>
            <p>L'appareil photo sert à scanner les QR codes : l'image est analysée sur le téléphone et n'est jamais envoyée. L'application ne collecte ni votre position, ni d'identifiant publicitaire, et ne contient aucune publicité.</p>

            <h2>Utilisation des données</h2>
            <ul>
                <li>Faire fonctionner l'application : tenir les caisses, calculer les tours, montrer à chacun sa situation.</li>
                <li>Identifier votre compte et le protéger.</li>
                <li>Permettre au bureau de valider les paiements déclarés et les demandes d'adhésion.</li>
            </ul>
            <p>Les rappels et le point du tour partagés sur WhatsApp sont envoyés par vous, depuis votre téléphone : l'application prépare le message, elle ne l'envoie pas à votre place.</p>

            <h2>Qui voit quoi</h2>
            <ul>
                <li>Le bureau d'une caisse (président(e), trésorier(e)) voit les membres, les cotisations et les dépenses de cette caisse.</li>
                <li>Un membre voit sa propre situation dans chaque caisse où il est inscrit, jamais les paiements des autres.</li>
            </ul>

